#!/usr/bin/env bash
# Packs the generated bindings into a real wheel, installs it, and uses it.
#
#   1. stage a project: the generated package, the wasm binary, and the PEP 517
#      backend from `pack/`
#   2. ask pip for a wheel (pip drives the backend, so this is the PEP 517 path
#      and not a shortcut around it)
#   3. pip install the wheel into a throwaway venv
#   4. run `scripts/wheel_smoke.py` from outside the repository, so the import
#      has to resolve to the installed package
#
# Usage:
#   scripts/wheel.sh              # needs `_gen/` and the release wasm to exist
#   scripts/wheel.sh --keep-venv  # leave the venv behind for inspection
#
# Requirements: moon (already built), python + pip, wasmtime installed for the
# interpreter the venv borrows its site-packages from.
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/.." && pwd)
OUT="${GEN_OUT:-$ROOT/_gen}"
WASM="$ROOT/_build/wasm/release/build/guest_gen/guest_gen.wasm"
DIST="$ROOT/dist"
STAGE="$DIST/project"
VENV="$DIST/venv"
KEEP_VENV=0

for arg in "$@"; do
  case "$arg" in
    --keep-venv) KEEP_VENV=1 ;;
    *) echo "unknown argument: $arg" >&2; exit 2 ;;
  esac
done

if command -v python3 >/dev/null 2>&1; then
  PYTHON=python3
else
  PYTHON=python
fi

cd "$ROOT"

if [ ! -d "$OUT/moonbridge" ]; then
  echo "no generated package at $OUT; run scripts/e2e.sh first" >&2
  exit 1
fi
if [ ! -f "$WASM" ]; then
  echo "no guest wasm at $WASM; run scripts/e2e.sh first" >&2
  exit 1
fi

# The version comes from the MoonBit module, so the wheel and `moon.mod` cannot
# disagree about what was built.
VERSION=$(sed -n 's/^version *= *"\(.*\)"/\1/p' moon.mod | head -1)
if [ -z "$VERSION" ]; then
  echo "could not read the version from moon.mod" >&2
  exit 1
fi

echo
echo "== staging the wheel project =="
rm -rf "$STAGE"
mkdir -p "$STAGE"
cp -r "$OUT/moonbridge" "$STAGE/moonbridge"
# The binary goes inside the package, so `moonbridge.install()` finds it with
# nothing but `__file__`.
cp "$WASM" "$STAGE/moonbridge/_guest.wasm"
cp pack/pyproject.toml pack/moonbridge_build.py "$STAGE/"
cat > "$STAGE/moonbridge_wheel.json" <<JSON
{
  "name": "moonbridge",
  "version": "$VERSION",
  "package": "moonbridge",
  "summary": "Python bindings for MoonBit packages, generated by MoonBridge",
  "description": "Generated bindings for moonbitlang/core (json, builtin, lexbuf) and the MoonBridge callback probe. The guest module is wasm and is loaded through wasmtime, which is why it is a runtime dependency rather than an optional one.",
  "requires": ["wasmtime>=20"]
}
JSON
echo "staged $(find "$STAGE/moonbridge" -type f | wc -l) files for version $VERSION"

echo
echo "== building the wheel through PEP 517 =="
rm -rf "$DIST"/*.whl
# `--no-build-isolation` because the backend declares no build requirements:
# an isolated environment would only add a venv to create. `--no-deps` because
# a dependency-free wheel has nothing to resolve and the index is not consulted.
"$PYTHON" -m pip wheel --no-build-isolation --no-deps -w "$DIST" "$STAGE" 2>&1 |
  sed 's/^/  /'
WHEEL=$(ls "$DIST"/*.whl | head -1)
echo "built $(basename "$WHEEL") ($(wc -c < "$WHEEL") bytes)"

echo
echo "== installing it =="
rm -rf "$VENV"
# `--system-site-packages` so `wasmtime` is visible without downloading it: this
# script proves the wheel installs, not that pip can reach the network.
"$PYTHON" -m venv --system-site-packages "$VENV"
if [ -x "$VENV/Scripts/python.exe" ]; then
  VENV_PY="$VENV/Scripts/python.exe"
else
  VENV_PY="$VENV/bin/python"
fi
"$VENV_PY" -m pip install --no-deps --force-reinstall "$WHEEL" 2>&1 | sed 's/^/  /'
"$VENV_PY" -m pip show moonbridge | sed -n '1,3p' | sed 's/^/  /'

echo
echo "== using the installed wheel =="
# Run from `dist/`, not from the repository: `import moonbridge` must resolve to
# the installed package, and from the repo root it would not.
(cd "$DIST" && "$VENV_PY" "$ROOT/scripts/wheel_smoke.py")

if [ "$KEEP_VENV" -eq 0 ]; then
  rm -rf "$VENV"
else
  echo
  echo "venv kept at $VENV"
fi

echo
echo "wheel: $WHEEL"
